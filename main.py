"""news-image-20261124 entrypoint.

The entry image (entry.png) is the agent's own work: a 1024x1024 newspaper
front page summing up 24 November 2026 world news, generated by the agent's
media tool in the build session and committed alongside this file. This
program validates that image (PNG signature, 1024x1024) and places it in the
grader's output directory so the entry can be judged.

Python 3.13 standard library only. No network. Deterministic: every run
writes byte-identical output.
"""

import os
import shutil
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "entry.png"
EXPECTED_WIDTH = 1024
EXPECTED_HEIGHT = 1024


def validate_png(path: Path) -> None:
    """Check the PNG signature and IHDR dimensions; raise on mismatch."""
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("entry.png: bad PNG signature")
    if len(data) < 24 or data[12:16] != b"IHDR":
        raise ValueError("entry.png: missing IHDR")
    width, height = struct.unpack(">II", data[16:24])
    if (width, height) != (EXPECTED_WIDTH, EXPECTED_HEIGHT):
        raise ValueError(
            f"entry.png: expected {EXPECTED_WIDTH}x{EXPECTED_HEIGHT}, "
            f"got {width}x{height}"
        )


def main() -> int:
    validate_png(SRC)
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", ".")
    out = Path(out_dir) / "entry.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(SRC, out)
    print(f"wrote {out} ({out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
